#!/usr/bin/env python3
"""Generate TFT_eSPI smooth (VLW) fonts from Noto Sans as C arrays -> include/fonts.h"""
import struct, sys
from PIL import Image, ImageDraw, ImageFont

REG = "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"
BOLD = "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"
ASCII = "".join(chr(c) for c in range(32, 127)) + "°·"
NUM = "0123456789.,-%/ "
BIGNUM = "0123456789.- "

FONTS = [  # name, ttf, px size, charset
    ("font_label", BOLD, 11, ASCII),
    ("font_body", REG, 13, ASCII),
    ("font_bodyb", BOLD, 14, ASCII),
    ("font_title", BOLD, 18, ASCII),
    ("font_val", BOLD, 24, NUM),
    ("font_big", BOLD, 46, BIGNUM),
]

def build(ttf, size, chars):
    f = ImageFont.truetype(ttf, size)
    asc = -f.getbbox("d", anchor="ls")[1]
    desc = f.getbbox("p", anchor="ls")[3]
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        pad = size
        img = Image.new("L", (size * 3, size * 3), 0)
        base = size * 2
        ImageDraw.Draw(img).text((pad, base), ch, font=f, fill=255, anchor="ls")
        bb = img.getbbox()
        adv = int(round(f.getlength(ch)))
        if bb is None:
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        l, t, r, b = bb
        w, h = r - l, b - t
        data = img.crop(bb).tobytes()
        glyphs.append((ord(ch), h, w, adv, base - t, l - pad, data))
    out = struct.pack(">6i", len(glyphs), 11, size, 0, asc, desc)
    for u, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return out

with open(sys.argv[1] if len(sys.argv) > 1 else "include/fonts.h", "w") as fh:
    fh.write("// generated by tools/make_fonts.py - do not edit\n#pragma once\n#include <pgmspace.h>\n\n")
    for name, ttf, size, chars in FONTS:
        d = build(ttf, size, chars)
        fh.write(f"// {name}: {ttf.split('/')[-1]} {size}px, {len(d)} bytes\n")
        fh.write(f"const uint8_t {name}[] PROGMEM = {{\n")
        for i in range(0, len(d), 24):
            fh.write("  " + ",".join(f"0x{b:02X}" for b in d[i:i + 24]) + ",\n")
        fh.write("};\n\n")
        print(name, len(d))
